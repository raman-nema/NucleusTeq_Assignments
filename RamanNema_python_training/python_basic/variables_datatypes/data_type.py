# Program to demonstrate basic Python data types.

def display_data_types():
    # Create variables and display their data types.
    student_name = "Raman"
    age = 24
    percentage = 85.5
    is_passed = True

    print("Student Name:", student_name ,"| Type:", type(student_name))
    print("Age:", age ,"| Type:", type(age) )
    print("Percentage:", percentage ,"| Type:", type(percentage) )
    print("Passed:", is_passed ,"| Type:", type(is_passed))

display_data_types()